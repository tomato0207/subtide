"""
Chapter summaries from cached subtitles, generated by a local Ollama model.

Subtitles are split into time-based sections (cut at pauses), each section gets a
short title + summary, plus a one-paragraph overview of the whole video.
Jobs run in a background thread; callers poll get_summary_status().
"""

import json
import logging
import os
import threading
from typing import Any, Dict, List, Optional

import requests

from backend.config import (
    SUMMARY_MODEL, SUMMARY_OLLAMA_URL, SUMMARY_KEEP_ALIVE,
)
from backend.utils.file_utils import get_cache_path

logger = logging.getLogger('subtide')
LOG_PREFIX = "[SUMMARY]"

# Section length: ~1/10 of the video, between 1.5 and 5 minutes
MIN_SECTION_MS = 90 * 1000
MAX_SECTION_MS = 300 * 1000
# Prefer cutting at a pause at least this long once a section reaches its target length
CUT_GAP_MS = 800
# Cap transcript characters sent per section (keeps prompts within num_ctx)
MAX_SECTION_CHARS = 3000

SECTION_PROMPT = (
    "你是影片與課程的筆記助手。根據逐字稿片段，用繁體中文（台灣用語）寫出這一段的標題與摘要。"
    "逐字稿由語音辨識產生，可能有錯字，請依上下文理解，不要照抄錯字。"
    "只輸出 JSON：{\"title\": \"...\", \"summary\": \"...\"}。"
    "title 不超過 15 個字，點出這段的主題；summary 不超過 60 個字，說明這段講了什麼重點。"
)
OVERVIEW_PROMPT = (
    "你是影片與課程的筆記助手。根據各段落的標題與摘要，用繁體中文（台灣用語）寫出整部影片的總結。"
    "只輸出 JSON：{\"overview\": \"...\"}，overview 不超過 100 個字。"
)

_jobs: Dict[str, Dict[str, Any]] = {}
_jobs_lock = threading.Lock()
# One summary at a time: the local model shares the GPU with Whisper
_gpu_slot = threading.Semaphore(1)


def _format_ts(ms: int) -> str:
    total = int(ms // 1000)
    h, rem = divmod(total, 3600)
    m, s = divmod(rem, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m:02d}:{s:02d}"


def split_sections(subtitles: List[Dict[str, Any]]) -> List[List[Dict[str, Any]]]:
    """Split subtitles (ms timestamps) into sections, cutting at pauses near the target length."""
    if not subtitles:
        return []
    total_ms = subtitles[-1]['end'] - subtitles[0]['start']
    target = min(max(total_ms / 10, MIN_SECTION_MS), MAX_SECTION_MS)

    sections: List[List[Dict[str, Any]]] = []
    current: List[Dict[str, Any]] = []
    for i, sub in enumerate(subtitles):
        current.append(sub)
        if i + 1 >= len(subtitles):
            break
        duration = sub['end'] - current[0]['start']
        gap = subtitles[i + 1]['start'] - sub['end']
        if (duration >= target and gap >= CUT_GAP_MS) or duration >= target * 1.5:
            sections.append(current)
            current = []

    if current:
        # Merge a short tail into the previous section
        if sections and current[-1]['end'] - current[0]['start'] < target * 0.3:
            sections[-1].extend(current)
        else:
            sections.append(current)
    return sections


def _chat_json(system: str, user: str) -> Dict[str, Any]:
    """Call Ollama /api/chat in JSON mode and parse the reply."""
    response = requests.post(
        f"{SUMMARY_OLLAMA_URL.rstrip('/')}/api/chat",
        json={
            'model': SUMMARY_MODEL,
            'messages': [
                {'role': 'system', 'content': system},
                {'role': 'user', 'content': user},
            ],
            'stream': False,
            'format': 'json',
            'keep_alive': SUMMARY_KEEP_ALIVE,
            'options': {'temperature': 0.3, 'num_ctx': 4096},
        },
        timeout=300,
    )
    response.raise_for_status()
    return json.loads(response.json()['message']['content'])


def _load_subtitles(video_id: str, lang: str) -> Optional[List[Dict[str, Any]]]:
    path = get_cache_path(video_id, f'translated_{lang}')
    if not os.path.exists(path):
        return None
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    subs = data.get('subtitles') if isinstance(data, dict) else data
    return [s for s in (subs or []) if (s.get('translatedText') or s.get('text'))]


def _load_title(video_id: str) -> Optional[str]:
    path = get_cache_path(video_id, 'title')
    if os.path.exists(path):
        try:
            with open(path, 'r', encoding='utf-8') as f:
                return json.load(f).get('title')
        except (OSError, ValueError):
            pass
    return None


def _run_job(key: str, video_id: str, lang: str, subtitles: List[Dict[str, Any]]):
    from backend.services.whisper_service import convert_chinese_text

    job = _jobs[key]
    try:
        with _gpu_slot:
            job['status'] = 'running'
            sections = split_sections(subtitles)
            job['total'] = len(sections)
            title = _load_title(video_id) or ''
            logger.info(f"{LOG_PREFIX} {video_id}: {len(sections)} sections with {SUMMARY_MODEL}")

            chapters = []
            prev_title = ''
            for section in sections:
                text = ' '.join(s.get('translatedText') or s['text'] for s in section)[:MAX_SECTION_CHARS]
                start, end = section[0]['start'], section[-1]['end']
                user = (
                    f"影片標題：{title}\n"
                    f"上一段主題：{prev_title or '（這是第一段）'}\n"
                    f"逐字稿（{_format_ts(start)}–{_format_ts(end)}）：\n{text}"
                )
                try:
                    reply = _chat_json(SECTION_PROMPT, user)
                    chapter_title = str(reply.get('title', '')).strip()
                    summary = str(reply.get('summary', '')).strip()
                except (requests.RequestException, ValueError, KeyError) as e:
                    if isinstance(e, requests.ConnectionError):
                        raise
                    logger.warning(f"{LOG_PREFIX} Section at {_format_ts(start)} failed: {e}")
                    chapter_title, summary = '', ''
                chapter_title = convert_chinese_text(chapter_title) or text[:15]
                chapters.append({
                    'start': start,
                    'end': end,
                    'title': chapter_title,
                    'summary': convert_chinese_text(summary),
                })
                prev_title = chapter_title
                job['progress'] = len(chapters)

            overview = ''
            if len(chapters) > 1:
                outline = '\n'.join(f"{_format_ts(c['start'])} {c['title']}：{c['summary']}" for c in chapters)
                try:
                    overview = convert_chinese_text(str(_chat_json(OVERVIEW_PROMPT, f"影片標題：{title}\n{outline}").get('overview', '')).strip())
                except (requests.RequestException, ValueError, KeyError) as e:
                    logger.warning(f"{LOG_PREFIX} Overview failed: {e}")

        result = {'chapters': chapters, 'overview': overview, 'model': SUMMARY_MODEL}
        with open(get_cache_path(video_id, f'summary_{lang}'), 'w', encoding='utf-8') as f:
            json.dump(result, f, ensure_ascii=False, indent=2)
        logger.info(f"{LOG_PREFIX} {video_id}: done ({len(chapters)} chapters)")
        with _jobs_lock:
            _jobs.pop(key, None)
    except Exception as e:
        logger.exception(f"{LOG_PREFIX} {video_id}: failed")
        message = 'Cannot connect to Ollama' if isinstance(e, requests.ConnectionError) else str(e)[:200]
        job.update(status='error', error=message)


def get_summary_status(video_id: str, lang: str) -> Dict[str, Any]:
    """Return the cached summary, or the state of its background job (starting one if needed)."""
    cache_path = get_cache_path(video_id, f'summary_{lang}')
    if os.path.exists(cache_path):
        with open(cache_path, 'r', encoding='utf-8') as f:
            return {'status': 'done', **json.load(f)}

    key = f"{video_id}:{lang}"
    with _jobs_lock:
        job = _jobs.get(key)
        if job:
            if job['status'] == 'error':
                # Report the error once; the next request retries
                _jobs.pop(key, None)
            return dict(job)

        subtitles = _load_subtitles(video_id, lang)
        if not subtitles:
            return {'status': 'no_subtitles'}

        job = {'status': 'queued', 'progress': 0, 'total': 0}
        _jobs[key] = job
    threading.Thread(target=_run_job, args=(key, video_id, lang, subtitles), daemon=True).start()
    return dict(job)
